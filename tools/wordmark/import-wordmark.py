"""Converts the Gentle Shell lettering of gentlemanprogramming.com into the
pixel rows the app draws (apps/desktop/src/brand/mask.ts).

The page draws the lettering in a <pre class="home-wordmark"> with half blocks:
each character is two pixels tall (top half, bottom half, both) and a shadow
character sits in a span of class alive-wm-shadow. This reads the saved page as
DATA only (never run anything from it):

    python -I tools/wordmark/import-wordmark.py <saved-page.html> apps/desktop/src/brand/mask.ts

Output alphabet: '#' a lettering pixel, 's' a shadow pixel, '.' nothing.
"""
import html
import re
import sys

TOP, BOTTOM, BOTH, SHADE = '\u2580', '\u2584', '\u2588', '\u2592'


def chars_of(line):
    out = []
    for part in re.split(r'(<span class="alive-wm-shadow">.*?</span>)', line):
        shadow = part.startswith('<span')
        text = html.unescape(re.sub(r'<[^>]+>', '', part))
        out += [(c, shadow) for c in text]
    return out


def pixels(char, shadow):
    if char == SHADE or (shadow and char != ' '):
        return 's', 's'
    return ('#' if char in (TOP, BOTH) else '.'), ('#' if char in (BOTTOM, BOTH) else '.')


def main(page, target):
    source = open(page, encoding='utf-8').read()
    pre = re.search(r'<pre class="home-wordmark"[^>]*>(.*?)</pre>', source, re.S).group(1)
    lines = [chars_of(line) for line in pre.split('\n')]
    width = max(len(line) for line in lines)
    rows = []
    for line in lines:
        top, bottom = '', ''
        for c in range(width):
            t, b = pixels(*line[c]) if c < len(line) else ('.', '.')
            top, bottom = top + t, bottom + b
        rows += [top, bottom]
    while rows and set(rows[-1]) == {'.'}:
        rows.pop()
    body = (
        "// The \"Gentle Shell\" lettering as a pixel grid: '#' a pixel of the letters,\n"
        "// 's' a shadow pixel, '.' nothing. Generated by tools/wordmark/import-wordmark.py\n"
        "// from the lettering on gentlemanprogramming.com (see NOTICE.md), so the app\n"
        "// needs no font at run time.\n\nexport const MASK: string[] = [\n"
        + ''.join("  '%s',\n" % r for r in rows)
        + ']\n'
    )
    open(target, 'w', newline='\n', encoding='ascii').write(body)
    print(len(rows), 'rows x', width, 'columns')


main(sys.argv[1], sys.argv[2])
